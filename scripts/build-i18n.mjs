const rows = readFileSync(new URL("./catalog.tsv", import.meta.url), "utf8").split(/\r?\n/).filter(Boolean);
const header = rows.shift().split("\t");
if (header.slice(1).join() !== LANGS.join()) throw new Error("Unexpected catalog columns: " + header.join());

const out = Object.fromEntries(LANGS.map((l) => [l, {}]));
for (const row of rows) {
  const [key, ...values] = row.split("\t");
  if (SKIP.test(key)) continue;
  LANGS.forEach((l, i) => (out[l][key] = values[i]));
}
for (const [key, values] of Object.entries(OVERRIDES)) LANGS.forEach((l, i) => (out[l][key] = values[i]));
for (const l of LANGS) if (Object.values(out[l]).some((v) => !v)) throw new Error("Missing translation in " + l);

writeFileSync(new URL("../public/i18n.js", import.meta.url), "// Generated by scripts/build-i18n.mjs — do not edit.\nwindow.I18N = " + JSON.stringify(out) + ";\n");
